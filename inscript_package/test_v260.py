print("\n── 7. Stdlib versioning ───────────────────────────────────────────────")

_tmp_stdlib = make_tmpdir()

try:
    from inscript import VERSION as _V

    # No toml → 0 (no constraint to check)
    ret_no_toml = check_stdlib_version(_tmp_stdlib)
    check("no toml → stdlib check passes", ret_no_toml, 0)

    # Toml with no stdlib key → 0
    write_toml(_tmp_stdlib, "[package]\nname = \"mygame\"\nversion = \"1.0.0\"\n")
    ret_no_key = check_stdlib_version(_tmp_stdlib)
    check("no stdlib key → passes", ret_no_key, 0)

    # Satisfied constraint (current version exactly)
    write_toml(_tmp_stdlib, f'[package]\nname = "mygame"\nversion = "1.0.0"\nstdlib = ">={_V}"\n')
    ret_ok = check_stdlib_version(_tmp_stdlib)
    check("satisfied constraint (>=current) returns 0", ret_ok, 0)

    # Unsatisfied constraint (require far-future version)
    write_toml(_tmp_stdlib, '[package]\nname = "mygame"\nversion = "1.0.0"\nstdlib = ">=99.0.0"\n')
    ret_fail = check_stdlib_version(_tmp_stdlib)
    check("unsatisfied constraint returns 1", ret_fail, 1)

    # Exact version match
    write_toml(_tmp_stdlib, f'[package]\nname = "mygame"\nversion = "1.0.0"\nstdlib = "^{_V}"\n')
    ret_caret = check_stdlib_version(_tmp_stdlib)
    check("caret constraint on current version returns 0", ret_caret, 0)

finally:
    shutil.rmtree(_tmp_stdlib, ignore_errors=True)

