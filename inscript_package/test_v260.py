print("\n── 6. Monorepo / workspace support ────────────────────────────────────")

_tmp_mono = make_tmpdir()

try:
    # No workspace key → empty list
    write_toml(_tmp_mono, "[package]\nname = \"root\"\nversion = \"1.0.0\"\n")
    members = _resolve_workspace_packages(_tmp_mono)
    check("no workspace key → empty list", members, [])

    # Create two sub-packages
    pkg_a = os.path.join(_tmp_mono, "packages", "pkg-a")
    pkg_b = os.path.join(_tmp_mono, "packages", "pkg-b")
    os.makedirs(pkg_a); os.makedirs(pkg_b)
    write_toml(pkg_a, "[package]\nname = \"pkg-a\"\nversion = \"0.1.0\"\n")
    write_toml(pkg_b, "[package]\nname = \"pkg-b\"\nversion = \"0.2.0\"\n")

    # Write root manifest with workspace glob (top-level key, not inside [package])
    write_toml(_tmp_mono, '[package]\nname = "root"\nversion = "1.0.0"\n\nworkspace = ["packages/*"]\n')

    members2 = _resolve_workspace_packages(_tmp_mono)
    names = sorted([m[0] for m in members2])
    check("workspace discovers 2 members", len(members2), 2)
    check("member names resolved", names, ["pkg-a", "pkg-b"])

    # workspace_list should return 0
    ret_list = workspace_list(_tmp_mono)
    check("workspace_list returns 0", ret_list, 0)

    # Member with no inscript.toml is skipped
    pkg_c = os.path.join(_tmp_mono, "packages", "pkg-c")
    os.makedirs(pkg_c)
    # No manifest → should be skipped
    members3 = _resolve_workspace_packages(_tmp_mono)
    check("member without toml is skipped", len(members3), 2)

    # workspace_install with no deps → 0
    ret_ws_install = workspace_install(_tmp_mono)
    check("workspace_install with no deps returns 0", ret_ws_install, 0)

finally:
    shutil.rmtree(_tmp_mono, ignore_errors=True)

