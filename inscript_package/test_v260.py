# 3. Config system
# ─────────────────────────────────────────────────────────────────────────────
print("\n── 3. Config system ───────────────────────────────────────────────────")

# Use a temp config path to avoid polluting real user config
import inscript as _ins_mod
_orig_config_path = _ins_mod.CONFIG_PATH
_tmp_config_dir   = make_tmpdir()
_ins_mod.CONFIG_PATH = os.path.join(_tmp_config_dir, "config.json")

try:
    # Fresh config is empty
    cfg = _read_config()
    check("fresh config is empty dict", cfg, {})

    # set
    ret = cmd_config(["set", "registry", "https://pkg.mygame.dev"])
    check("config set returns 0", ret, 0)

    cfg2 = _read_config()
    check("registry value stored", cfg2.get("registry"), "https://pkg.mygame.dev")

    # get
    import io as _io
    old_stdout = sys.stdout
    sys.stdout = _io.StringIO()
    cmd_config(["get", "registry"])
    out = sys.stdout.getvalue().strip()
    sys.stdout = old_stdout
    check("config get prints value", out, "https://pkg.mygame.dev")

    # list
    sys.stdout = _io.StringIO()
    cmd_config(["list"])
    out2 = sys.stdout.getvalue()
    sys.stdout = old_stdout
    check_contains("config list shows key", out2, "registry")
    check_contains("config list shows value", out2, "https://pkg.mygame.dev")

    # _get_registry_url honours override
    url = _get_registry_url()
    check("_get_registry_url uses config override", url, "https://pkg.mygame.dev")

    # unset
    cmd_config(["unset", "registry"])
    cfg3 = _read_config()
    check("config unset removes key", "registry" in cfg3, False)

    # _get_registry_url falls back to default after unset
    url2 = _get_registry_url()
    check("_get_registry_url falls back to default", url2, REGISTRY_URL)

    # unknown subcommand
    ret_bad = cmd_config(["badcmd"])
    check("unknown subcommand returns 1", ret_bad, 1)

    # missing args
    ret_nokey = cmd_config(["set", "only_one_arg"])
    check("set with missing value returns 1", ret_nokey, 1)

finally:
    _ins_mod.CONFIG_PATH = _orig_config_path
    shutil.rmtree(_tmp_config_dir, ignore_errors=True)

# ─────────────────────────────────────────────────────────────────────────────
# 4. publish_package() — local bundle validation (no live network)
# ─────────────────────────────────────────────────────────────────────────────
print("\n── 4. publish_package() ───────────────────────────────────────────────")

_tmp_pub = make_tmpdir()
_tmp_cfg_pub = make_tmpdir()
_ins_mod.CONFIG_PATH = os.path.join(_tmp_cfg_pub, "config.json")

try:
    # Missing inscript.toml → error
    ret_no_toml = publish_package(_tmp_pub)
    check("publish with no toml returns 1", ret_no_toml, 1)

    # toml with no [package] name → error
    write_toml(_tmp_pub, "[package]\nversion = \"1.0.0\"\n")
    ret_no_name = publish_package(_tmp_pub)
    check("publish with no name returns 1", ret_no_name, 1)

    # toml with name but no version → error
    write_toml(_tmp_pub, "[package]\nname = \"my-pkg\"\n")
    ret_no_ver = publish_package(_tmp_pub)
    check("publish with no version returns 1", ret_no_ver, 1)

    # valid toml but no api_key → error
    write_toml(_tmp_pub, "[package]\nname = \"my-pkg\"\nversion = \"1.0.0\"\n")
    os.makedirs(os.path.dirname(_ins_mod.CONFIG_PATH), exist_ok=True)
    ret_no_key = publish_package(_tmp_pub)
    check("publish with no api_key returns 1", ret_no_key, 1)

    # Set api_key and add a .ins file — bundle should form; upload will fail (no registry)
    _ins_mod._write_config({"api_key": "test-token-xyz"})
    with open(os.path.join(_tmp_pub, "main.ins"), "w") as f:
        f.write("let x = 42\nprint(x)\n")
    ret_pub = publish_package(_tmp_pub)
    # Should return 1 (registry not live) but reach the upload step (sha256 printed)
    check("publish reaches upload step (returns 1 = registry not live)", ret_pub, 1)

    # No .ins files → error before upload
    tmp_empty = make_tmpdir()
    write_toml(tmp_empty, "[package]\nname = \"empty\"\nversion = \"0.1.0\"\n")
    ret_empty = publish_package(tmp_empty)
    check("publish with no .ins files returns 1", ret_empty, 1)
    shutil.rmtree(tmp_empty, ignore_errors=True)

finally:
    _ins_mod.CONFIG_PATH = _orig_config_path
    shutil.rmtree(_tmp_pub, ignore_errors=True)
    shutil.rmtree(_tmp_cfg_pub, ignore_errors=True)

# ─────────────────────────────────────────────────────────────────────────────
# 5. audit_packages() — offline structural checks
# ─────────────────────────────────────────────────────────────────────────────
print("\n── 5. audit_packages() ────────────────────────────────────────────────")

_tmp_audit = make_tmpdir()

try:
    # No lock file → clean exit
    ret_no_lock = audit_packages(_tmp_audit)
    check("audit with no lock returns 0", ret_no_lock, 0)

    # Empty lock (no packages) → clean
    write_lock(_tmp_audit, {})
    ret_empty_lock = audit_packages(_tmp_audit)
    check("audit with empty lock returns 0", ret_empty_lock, 0)

    # Lock with packages but no advisory file (offline) → prints warning, returns 0
    write_lock(_tmp_audit, {"math-utils": "1.0.0", "color-utils": "1.0.0"})
    # Stub ADVISORY_URL to a non-existent file so it falls through to offline mode
    old_adv_url = _ins_mod.ADVISORY_URL
    _ins_mod.ADVISORY_URL = "https://localhost:0/advisories_nonexistent.json"
    ret_offline = audit_packages(_tmp_audit)
    _ins_mod.ADVISORY_URL = old_adv_url
    # Offline: no vulns from advisory DB but may warn about missing dirs → return 0
    check("audit offline (no network) returns 0", ret_offline, 0)

    # Advisory matching via a temp file patched in
    adv_data = {
        "math-utils": [
            {
                "affected": "<1.0.1",
                "severity": "low",
                "description": "Off-by-one in gcd()",
                "fixed_in": "1.0.1"
            }
        ]
    }
    tmp_adv = os.path.join(_tmp_audit, "advisories.json")
    with open(tmp_adv, "w") as f:
        json.dump(adv_data, f)

    # Patch ADVISORY_URL to local file:// URL and lock to vulnerable version
    write_lock(_tmp_audit, {"math-utils": "1.0.0"})
    _ins_mod.ADVISORY_URL = "file://" + tmp_adv if sys.platform != "win32" else "file:///" + tmp_adv.replace("\\", "/")
    import urllib.request as _ur
    _orig_urlopen = _ur.urlopen
    def _mock_urlopen(url, timeout=None):
        # Serve our local file for advisory URL regardless of scheme
        if "advisories" in url:
            class _FakeResp:
                def read(self_): return json.dumps(adv_data).encode()
                def __enter__(self_): return self_
                def __exit__(self_, *a): pass
            return _FakeResp()
        return _orig_urlopen(url, timeout=timeout)
    _ur.urlopen = _mock_urlopen
    try:
        ret_vuln = audit_packages(_tmp_audit)
        check("audit finds vulnerability in affected package returns 1", ret_vuln, 1)
    finally:
        _ur.urlopen = _orig_urlopen
        _ins_mod.ADVISORY_URL = old_adv_url

    # Non-vulnerable version → clean
    write_lock(_tmp_audit, {"math-utils": "1.0.1"})
    _ur.urlopen = _mock_urlopen
    try:
        ret_safe = audit_packages(_tmp_audit)
        check("audit finds no vuln for patched version returns 0", ret_safe, 0)
    finally:
        _ur.urlopen = _orig_urlopen

finally:
    shutil.rmtree(_tmp_audit, ignore_errors=True)

